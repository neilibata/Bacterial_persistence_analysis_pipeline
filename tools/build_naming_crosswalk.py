#!/usr/bin/env python3
"""Generate docs/naming_crosswalk.md: what each item is called in each place.

The same object has up to three names. The manuscript calls the roadmap
"Figure S31"; this repository calls it
`results/combined/figure_s0_roadmap.png`; the deposit calls it
`S31_figure_s0_roadmap.png`. Someone holding the submitted documents and the
GitHub repository has no way to line those up without a table, and the names
that are easiest to guess are the ones most likely to be wrong -- the August
document's A-numbers look like the S-numbers and no longer correspond to them.

Everything here is read out of the files that already define it -- the figure
manifest and tools/paper_manifest.csv -- except the Data S assignments, which
no file derives and which are therefore declared below with their evidence.

    python tools/build_naming_crosswalk.py          # write the document
    python tools/build_naming_crosswalk.py --check  # report gaps, write nothing
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT_MD = ROOT / "docs" / "naming_crosswalk.md"

#: Record A is published; its id is the one download_data.sh fetches.
RECORD_A_ID = "23437518"
RECORD_A_DOI = "10.5281/zenodo.23437518"

#: The four Data S items, which are the journal's name for the supporting
#: data files. Nothing in the pipeline derives this mapping -- it is an
#: editorial decision about what Science calls each file -- so it is declared
#: here, with where each one is drawn in the roadmap (Figure S31) as the
#: evidence that the document and the repository agree.
DATA_S = [
    ("Data S1", "the figure-data workbook",
     "`Data_S1_figure_data.xlsx`, built by `tools/build_data_s1.py`",
     "built from the stored data object behind every supplementary figure; "
     "those objects are in Record B",
     "Record B, as `Data_S1_figure_data.xlsx`"),
    ("Data S2", "Metadata Table M1 — curated per-sample metadata",
     "`Data_S2_metadata_M1.xlsx`, built from `final_run/metadata_M1.csv` by "
     "`tools/build_data_s2.py`, which verifies every cell against it",
     "badged *Data S2* on the curated-metadata and final-cohort boxes of "
     "Figure S31",
     "Record A as `metadata_M1.csv`; Record B as "
     "`Data_S2_metadata_M1.xlsx`"),
    ("Data S3", "Metadata Table M2 — the reference catalogues",
     "`metadata_M2.xlsx`",
     "badged *Data S3* on the combined-reference box of Figure S31",
     "Record B, as `Data_S3_metadata_M2.xlsx`"),
    ("Data S4", "Metadata Table M3 — the VANISH/BloSSUM taxon lists",
     "`metadata_M3.xlsx`",
     "badged *Data S4* on the taxon-list box of Figure S31",
     "Record B, as `Data_S4_metadata_M3.xlsx`"),
]

#: Which membership M3 describes is the question that matters, so the document
#: answers it rather than leaving a reader to infer it from a path.
SECOND_COPY_NOTE = (
    "M3 describes the taxon lists the reported run derived, committed under "
    "`metadata/lists_as_analysed/`. `tools/make_submission.py` rebuilds it from "
    "`results/` after a run, and that build writes the snapshot back, so the "
    "workbook and the lists it describes cannot disagree."
)


def slot_num(slot: str) -> int:
    return int(slot.lstrip("Ss"))


def figure_rows():
    from tools import figure_sets
    rows = []
    for slot, ref, stem in sorted(figure_sets.manifest(), key=lambda r: slot_num(r[0])):
        n = slot_num(slot)
        rows.append({
            "manuscript": f"Figure S{n}",
            "output": f"results/{ref}/{stem}.png",
            "deposit": f"S{n:02d}_{Path(stem).name}.png",
        })
    return rows


def manifest_rows(categories):
    rows = []
    for line in (ROOT / "tools" / "paper_manifest.csv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("|")
        if len(parts) < 6 or parts[0] == "item_id":
            continue
        if parts[1] in categories:
            rows.append({"item": parts[0], "source": parts[3], "what": parts[5]})
    return rows


def render(figs, tables, metadata) -> str:
    L = []
    w = L.append
    w("# What each item is called, where\n")
    w("<!-- Generated by tools/build_naming_crosswalk.py. Do not edit by hand:")
    w("     rebuild it, so it stays tied to the figure manifest and the paper")
    w("     manifest rather than drifting from them. -->\n")

    w("The same object carries up to three names:\n")
    w("| Vocabulary | Used by | Example |")
    w("| --- | --- | --- |")
    w("| **Manuscript** | the submitted `.docx` files, and the journal | Figure S31 |")
    w("| **Repository** | this tree, and the pipeline's own output paths | `results/combined/figure_s0_roadmap.png` |")
    w("| **Deposit** | the Zenodo records, and the flat `supplementary_figures/` view | `S31_figure_s0_roadmap.png` |\n")

    w("The deposit name is the manuscript number, zero-padded to two digits,")
    w("followed by the output's own filename — so sorting the deposit by name")
    w("gives the order the supplement presents them in.\n")

    w("> **The A-numbers are not the S-numbers.** The August source document")
    w("> (`Additional_figures_080826.docx`) numbered these A1–A31, and that")
    w("> mapping was once the identity. It is not any more, and it is not even")
    w("> a permutation: one figure moved to the main text, two slots were added")
    w("> and retired, a new figure took S1, and two runs of slots rotated on")
    w("> 2026-10-19. Match a figure by its path stem, never by assuming its old")
    w("> number.\n")

    w("## Supplementary figures\n")
    w(f"All {len(figs)} of them, in the order the supplement presents them.\n")
    w("| Manuscript | Repository output | Deposit filename |")
    w("| --- | --- | --- |")
    for r in figs:
        w(f"| **{r['manuscript']}** | `{r['output']}` | `{r['deposit']}` |")
    w("")

    w("## Data S1–S4\n")
    w("The journal's name for the supporting data files. Note that **Data S2,")
    w("S3 and S4 are Metadata Tables M1, M2 and M3** — the repository and the")
    w("manuscript use different names for the same three tables.\n")
    w("| Manuscript | What it is | Repository | Where it is kept |")
    w("| --- | --- | --- | --- |")
    for name, what, where, _evidence, record in DATA_S:
        w(f"| **{name}** | {what} | {where} | {record} |")
    w("")
    w("Evidence for each assignment, since no file in the pipeline derives it:\n")
    for name, _what, _where, evidence, _record in DATA_S:
        w(f"- **{name}** — {evidence}.")
    w("")
    w(SECOND_COPY_NOTE)
    w("")

    w("## Supplementary tables\n")
    w("| Manuscript | Built from |")
    w("| --- | --- |")
    for r in tables:
        src = f"`{r['source']}`" if r["source"] else "— (not produced by the pipeline)"
        w(f"| **{r['item'].replace('_', ' ')}** | {src} |")
    w("")

    w("## Metadata tables\n")
    w("The repository's own name for the three tables, alongside the")
    w("manuscript's. `Data S` is what the submitted documents call them.\n")
    w("| Repository | Manuscript | Built from |")
    w("| --- | --- | --- |")
    _ds = {"Metadata_M1": "Data S2", "Metadata_M2": "Data S3",
           "Metadata_M3": "Data S4"}
    for r in metadata:
        src = f"`{r['source']}`" if r["source"] else "—"
        w(f"| {r['item'].replace('_', ' ')} | {_ds.get(r['item'], '—')} | {src} |")
    w("")

    w("## The two deposit records\n")
    w(f"**Record A** — [`{RECORD_A_DOI}`](https://zenodo.org/records/{RECORD_A_ID})")
    w("holds the pipeline's *inputs*: the eight per-sample breadth and depth")
    w("matrices and the curated per-sample metadata, `metadata_M1.csv`, which")
    w("is Data S2. `download_data.sh` fetches it and verifies every checksum.\n")
    w("**Record B** holds the pipeline's *outputs*: every submitted figure")
    w("loose and uncompressed, one file per figure under the deposit names")
    w("above, plus the result tables and the data object behind each figure,")
    w("archived per reference. `tools/build_data_s1.py` builds Data S1 from")
    w("those data objects, and the workbook it builds is deposited there too,")
    w("so Data S1 need not be rebuilt to be read.\n")
    w("Record B also carries all four Data S items as single files, each named")
    w("for both schemes at once — `Data_S2_metadata_M1.xlsx` and its two")
    w("siblings. The manuscript cites them as Data S2–S4; the pipeline, this")
    w("repository and Figure S31 call the same tables Metadata Tables M1–M3.")
    w("A reader who has only the deposit sees the file list before any")
    w("manifest, so the mapping has to hold in the filename itself.\n")
    w("Metadata Table M1 is therefore in both records: Record A carries the")
    w("`metadata_M1.csv` the pipeline reads and `download_data.sh` verifies,")
    w("and Record B carries the same table as the submitted workbook. M2 and")
    w("M3 are small enough to stay committed here as well.\n")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="report gaps and write nothing")
    a = ap.parse_args()

    figs = figure_rows()
    tables = manifest_rows({"supp_table"})
    metadata = manifest_rows({"metadata"})

    gaps = [r["item"] for r in tables if not r["source"]]
    print(f"  {len(figs)} figures, {len(DATA_S)} Data S items, "
          f"{len(tables)} tables, {len(metadata)} metadata tables")
    if gaps:
        print(f"  [note] {len(gaps)} table(s) with no pipeline source: "
              + ", ".join(gaps))
    if a.check:
        return 0

    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(render(figs, tables, metadata))
    print(f"  wrote {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
